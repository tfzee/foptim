#!/usr/bin/env python3
"""Builds the generic cost profile rows, the per row median of the real profiles.

Usage:
    scripts/make_generic_profile.py <out.csv> <cpu.csv>...
    scripts/make_generic_profile.py --check <generic.csv> <cpu.csv>...

Latency, reciprocal throughput, uops and size are medians, a port bit is set
when at least half of the profiles have it (the first profile if that leaves no
port). --check fails when the checked in file differs from what the inputs
produce, the cmake cost table step runs it so a stale file breaks the build.
"""

import csv
import statistics
import sys
from pathlib import Path

HEADER = """# GENERIC cost model data, the per row median of the supported microarchitectures.
# generated by scripts/make_generic_profile.py, do not edit by hand, rerun it
# when a microarchitecture is added or one of their csvs changes.
# ports_mask is over the abstract ports of Machine::kNumPorts.
op_class,latency,recip_throughput,ports_mask,n_uops,size_bytes
"""


def read(path):
    lines = [x for x in Path(path).read_text().splitlines(keepends=True)
             if not x.lstrip().startswith("#")]
    return list(csv.DictReader(lines))


def num(x):
    return f"{x:g}"


def build(inputs):
    tables = [read(p) for p in inputs]
    order = [r["op_class"] for r in tables[0]]
    by_name = [{r["op_class"]: r for r in t} for t in tables]
    out = HEADER
    for name in order:
        rows = [t[name] for t in by_name]
        med = lambda k: statistics.median(float(r[k]) for r in rows)
        masks = [int(r["ports_mask"], 16) for r in rows]
        mask = 0
        for bit in range(8):
            if sum(1 for m in masks if m >> bit & 1) * 2 >= len(masks):
                mask |= 1 << bit
        if mask == 0:
            mask = masks[0]
        out += "{},{},{},0x{:x},{},{}\n".format(
            name, num(med("latency")), num(med("recip_throughput")), mask,
            round(med("n_uops")), round(med("size_bytes")))
    return out


def main():
    args = sys.argv[1:]
    check = bool(args) and args[0] == "--check"
    if check:
        args = args[1:]
    if len(args) < 2:
        raise SystemExit(__doc__)
    text = build(args[1:])
    if check:
        if Path(args[0]).read_text() != text:
            raise SystemExit(
                f"{args[0]} is stale, run scripts/make_generic_profile.py "
                f"{args[0]} {' '.join(args[1:])}")
    else:
        Path(args[0]).write_text(text)


if __name__ == "__main__":
    main()
